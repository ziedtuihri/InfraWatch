CREATE SCHEMA IF NOT EXISTS infrawatch_warehouse;

CREATE TABLE IF NOT EXISTS infrawatch_warehouse.dim_resource (
    resource_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source TEXT NOT NULL,
    resource_type TEXT NOT NULL CHECK (
        resource_type IN ('host', 'vm', 'container', 'network', 'storage')
    ),
    external_id TEXT NOT NULL,
    name TEXT NOT NULL,
    parent_external_id TEXT,
    environment TEXT NOT NULL,
    state TEXT,
    attributes_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (source, resource_type, external_id)
);

CREATE TABLE IF NOT EXISTS infrawatch_warehouse.etl_run (
    run_id TEXT NOT NULL,
    source TEXT NOT NULL,
    environment TEXT NOT NULL,
    collected_at TEXT NOT NULL,
    PRIMARY KEY (run_id, source)
);

CREATE TABLE IF NOT EXISTS infrawatch_warehouse.fact_metric (
    resource_key BIGINT NOT NULL
        REFERENCES infrawatch_warehouse.dim_resource(resource_key),
    run_id TEXT NOT NULL,
    source TEXT NOT NULL,
    collected_at TEXT NOT NULL,
    metric_name TEXT NOT NULL,
    metric_value DOUBLE PRECISION NOT NULL,
    unit TEXT NOT NULL,
    PRIMARY KEY (resource_key, run_id, source, collected_at, metric_name),
    FOREIGN KEY (run_id, source)
        REFERENCES infrawatch_warehouse.etl_run(run_id, source)
);

CREATE INDEX IF NOT EXISTS idx_fact_metric_time
    ON infrawatch_warehouse.fact_metric (collected_at, metric_name);
CREATE INDEX IF NOT EXISTS idx_dim_resource_type
    ON infrawatch_warehouse.dim_resource (source, resource_type, environment);
